// Makes src/ReplicatedStorage/Shared/Maps/MapData.luau from Diego's docs/new-maps/maps.json (NEW MAPS FINALS zip,
// 2026-10-30) and prints a few layout values of his demos' layout(m) for MapLayout_Test.
// Run from the repo root: node tools/maps/make_mapdata.mjs
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const src = JSON.parse(fs.readFileSync(path.join(ROOT, "docs/new-maps/maps.json"), "utf8"));
const out = path.join(ROOT, "src/ReplicatedStorage/Shared/Maps/MapData.luau");

const KEYS = ["type", "x", "z", "w", "d", "round", "solid", "spin", "stairUp", "level", "height", "power"];
const lua = (v) => (typeof v === "string" ? JSON.stringify(v) : typeof v === "boolean" ? String(v) : String(v));
const list = (arr) => `{ ${arr.map(lua).join(", ")} }`;
const kv = (obj, keys) =>
	`{ ${(keys || Object.keys(obj)).filter((k) => obj[k] !== undefined).map((k) => `${k} = ${lua(obj[k])}`).join(", ")} }`;

const lines = [];
lines.push("--!strict");
lines.push("-- MapData: Diego's 11 sky maps (NEW MAPS FINALS zip, 2026-10-30; docs/new-maps/maps.json, symmetry already applied).");
lines.push("-- GENERATED by tools/maps/make_mapdata.mjs: do not edit by hand, change maps.json and run it again.");
lines.push("-- Studs. x = west->east, z = north->south (Roblox Z), an element's x/z is its north-west corner, w along X, d along Z;");
lines.push("-- floor top = local Y 0. Element types: zone, spawn (FFA), spawnA (pink) / spawnB (blue), wall, cover, deck, stair, pad.");
lines.push("");
lines.push("export type Element = {");
lines.push("\ttype: string,");
lines.push("\tx: number,");
lines.push("\tz: number,");
lines.push("\tw: number,");
lines.push("\td: number,");
lines.push("\tround: boolean?,");
lines.push("\tsolid: boolean?,");
lines.push("\tspin: boolean?,");
lines.push("\tstairUp: string?,");
lines.push("\tlevel: number?,");
lines.push("\theight: number?,");
lines.push("\tpower: string?,");
lines.push("}");
lines.push("export type Map = {");
lines.push("\tid: string,");
lines.push("\tmode: string, -- \"tdm\" | \"ffa\" | \"duel\"");
lines.push("\tname: string,");
lines.push("\tsub: string,");
lines.push("\tW: number,");
lines.push("\tH: number,");
lines.push("\tsymmetry: string,");
lines.push("\ttheme: { [string]: string },");
lines.push("\tdeco: { sky: string, amb: string, floor: string, pal: { string } },");
lines.push("\telements: { Element },");
lines.push("\tbotRoutes: { { name: string, points: { { number } } } },");
lines.push("}");
lines.push("");
const c = src.constants;
lines.push("local MapData = {}");
lines.push("");
lines.push("MapData.constants = {");
lines.push(`\tDECK_H = ${c.DECK_H},`);
lines.push(`\tDECK_SLAB = ${c.DECK_SLAB},`);
lines.push(`\tWALL_H = ${c.WALL_H},`);
lines.push(`\tCOVER_H = ${c.COVER_H},`);
lines.push(`\tSTAIR_STEPS = ${c.STAIR_STEPS},`);
lines.push(`\tCAP_H = ${c.WALL_CAP.h},`);
lines.push(`\tCAP_OVERHANG = ${c.WALL_CAP.overhang},`);
lines.push(`\tINK = ${lua(c.OUTLINE.color)},`);
lines.push(`\tOUTLINE = ${c.OUTLINE.thickness},`);
lines.push(`\tSPAWN_A = ${lua(c.SPAWN_COLORS.spawnA)},`);
lines.push(`\tSPAWN_B = ${lua(c.SPAWN_COLORS.spawnB)},`);
lines.push(`\tSKY_TOP = ${lua(c.SKY_GRADIENT.top)},`);
lines.push(`\tSKY_MID = ${lua(c.SKY_GRADIENT.mid)},`);
lines.push(`\tSKY_BOTTOM = ${lua(c.SKY_GRADIENT.bottom)},`);
lines.push("}");
lines.push("");
const order = [];
lines.push("MapData.maps = {} :: { [string]: Map }");
for (const [mode, maps] of Object.entries(src.modes)) {
	for (const m of maps) {
		order.push(m.id);
		lines.push(`MapData.maps.${m.id} = {`);
		lines.push(`\tid = ${lua(m.id)},`);
		lines.push(`\tmode = ${lua(mode)},`);
		lines.push(`\tname = ${lua(m.name)},`);
		lines.push(`\tsub = ${lua(m.sub)},`);
		lines.push(`\tW = ${m.size.W},`);
		lines.push(`\tH = ${m.size.H},`);
		lines.push(`\tsymmetry = ${lua(m.symmetry)},`);
		lines.push(`\ttheme = ${kv(m.theme)},`);
		lines.push(`\tdeco = { sky = ${lua(m.deco.sky)}, amb = ${lua(m.deco.amb)}, floor = ${lua(m.deco.floor)}, pal = ${list(m.deco.pal)} },`);
		lines.push("\telements = {");
		for (const e of m.elements) {
			for (const k of Object.keys(e)) if (!KEYS.includes(k)) throw new Error(`${m.id}: unknown element key ${k}`);
			lines.push(`\t\t${kv(e, KEYS)},`);
		}
		lines.push("\t},");
		lines.push("\tbotRoutes = {");
		for (const r of m.botRoutes) lines.push(`\t\t{ name = ${lua(r.name)}, points = { ${r.points.map((p) => list(p)).join(", ")} } },`);
		lines.push("\t},");
		lines.push("}");
	}
}
lines.push("");
lines.push(`-- Every map id, by mode then as in maps.json.`);
lines.push(`MapData.order = ${list(order)}`);
lines.push("");
lines.push("-- The ids of one mode (\"tdm\" | \"ffa\" | \"duel\"), in MapData.order.");
lines.push("function MapData.ofMode(mode: string): { string }");
lines.push("\tlocal ids = {}");
lines.push("\tfor _, id in MapData.order do");
lines.push("\t\tif MapData.maps[id].mode == mode then");
lines.push("\t\t\ttable.insert(ids, id)");
lines.push("\t\tend");
lines.push("\tend");
lines.push("\treturn ids");
lines.push("end");
lines.push("");
lines.push("return MapData");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`wrote ${out} (${order.length} maps)`);

// --- Diego's demo layout(m) (Duel/TDM/FFA Demo.dc.html, identical but FFA's bunting guard), for the test values ---
function srng(seed) { let s = 0; for (const ch of seed) s = (s * 31 + ch.charCodeAt(0)) >>> 0; return () => { s = (s + 0x6D2B79F5) >>> 0; let t = s; t = Math.imul(t ^ t >>> 15, t | 1); t ^= t + Math.imul(t ^ t >>> 7, t | 61); return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
function layout(m) {
	const sr = srng(m.id), r = (a, b) => a + sr() * (b - a), W = m.size.W, H = m.size.H, D = m.deco, RIM = 6, off = RIM / 2, L = { RIM, off };
	const ex = m.elements.map((e) => ({ t: e.type, x: e.x, y: e.z, w: e.w, h: e.d }));
	L.doodles = D.floor === "doodle" ? Array.from({ length: 110 }, (_, i) => ({ x: r(0, W), y: r(0, H), r: r(1, 3.5), k: i % 3, c: D.pal[i % 5] })) : [];
	L.cloudBed = Array.from({ length: 16 }, () => ({ r: r(16, 34), x: r(-10, W + 10), y: r(-26, -12), z: r(-10, H + 10), ph: r(0, 6), sp: r(0.3, 0.6) }));
	L.sparkles = Array.from({ length: 18 }, (_, i) => ({ x: r(4, W - 4), z: r(4, H - 4), ph: r(0, 1), sp: r(0.12, 0.25), c: ["#ffffff", "#ffe27a", "#ff7aa8", "#8fd8ff", "#b8f5c8"][i % 5] }));
	const corners = [[-off, -off], [W + off, -off], [W + off, H + off], [-off, H + off]]; L.posts = [];
	for (let i = 0; i < 4; i++) { const a = corners[i], b = corners[(i + 1) % 4], len = Math.hypot(b[0] - a[0], b[1] - a[1]), n = Math.max(1, Math.round(len / 26)); for (let k = 0; k < n; k++) L.posts.push([a[0] + (b[0] - a[0]) * k / n, a[1] + (b[1] - a[1]) * k / n]); }
	L.bunting = ex.some((e) => e.t === "spawnA") ? [0, 1].map((team) => { const sp = ex.find((e) => e.t === (team ? "spawnB" : "spawnA")), z0 = sp.y - 6, z1 = sp.y + sp.h + 6; return { team, x: team ? W + off : -off, z0, z1, nF: Math.round((z1 - z0) / 3.2) }; }) : [];
	L.splats = []; for (let i = 0; i < 10; i++) { const rr = r(1.4, 3.6), x = r(6, W / 2 - 6), z = r(6, H - 6), c = D.pal[i % D.pal.length]; L.splats.push({ r: rr, x, z, c }, { r: rr, x: W - x, z, c }); }
	const R0 = Math.hypot(W, H) / 2 + 45; L.sky = [];
	for (let i = 0; i < 14; i++) { const a = i / 14 * Math.PI * 2 + r(-0.15, 0.15), d = R0 + r(10, 150); L.sky.push({ i, x: W / 2 + Math.cos(a) * d, z: H / 2 + Math.sin(a) * d, y: r(-45, 50), s: r(1.1, 2.3), rx: r(-0.5, 0.5), ry: r(0, 6), rz: r(-0.4, 0.4), ph: r(0, 6), sp: r(0.3, 0.6), amp: r(2, 4), rs: r(-0.18, 0.18) }); }
	const up = D.amb === "bubble"; L.amb = Array.from({ length: 46 }, (_, i) => ({ x: r(4, W - 4), z: r(4, H - 4), y0: up ? 0.5 : 2, span: up ? 26 : 32, up, sp: up ? r(0.05, 0.1) : r(0.06, 0.12), ph: r(0, 1), wf: r(0.6, 1.4), wa: up ? 1.6 : 3, rx: up ? 0 : r(-3, 3), ry: r(-3, 3), s: up ? r(0.7, 1.5) : 1, c: D.pal[i % D.pal.length] }));
	return L;
}
const f = (n) => Number(n.toFixed(6));
for (const id of ["T3", "F2", "D1"]) {
	const m = Object.values(src.modes).flat().find((x) => x.id === id);
	const L = layout(m);
	const s0 = srng(id);
	console.log(id, JSON.stringify({ first: [f(s0()), f(s0())], posts: L.posts.length, bunting: L.bunting.length, sparkle0: [f(L.sparkles[0].x), f(L.sparkles[0].z)], splat3: [f(L.splats[3].r), f(L.splats[3].x), f(L.splats[3].z)], sky13: [f(L.sky[13].x), f(L.sky[13].y), f(L.sky[13].z), f(L.sky[13].rs)], amb45: [f(L.amb[45].x), f(L.amb[45].z), f(L.amb[45].ry)] }));
}
